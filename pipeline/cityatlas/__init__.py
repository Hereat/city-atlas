from pathlib import Path

# v2（2026-09-08）三件事一起发：
# * 分片里的城市改按面积排，平局取最小的那座（`directory.shard`）——先前按 cityID
#   （发号顺序）排，义乌的散步归了金华；
# * 画框改按两副轮廓求重叠（`frame.overlap_points`），中国 45 座变大，其余逐字不变；
# * 中文名统一走 `boundary.chinese_name`，认出了繁体名与名字后挂蒙文的那些，名单 1458 → 1462。
#
# 升版本的硬理由是**换掉分片的 URL**——App 的分片缓存永不过期，不换路径，
# 已经存过旧顺序的手机再也拿不到新答案。
#
# v3（2026-09-08）：**自治州与盟的驻地城市独立成城**（`pbf.CITY_LEVELS` 的
# `region_suffix`）。州的名字是一片区域的名字，人说「我在西昌」不说「我在凉山」，
# 而州的主城恰恰就在州府，先前州府被自己的州吞掉：在西昌散步，城市卡写着
# 「凉山彝族自治州」。33 个州/盟不再吞候补层，名单 1462 → 1483 座。
# 州本身留在名单里兜底——州域深处的县城只有它盖得住。
# 升版本除了换 URL，还为了 `CityStore.retryPending`：目录版本一变就重算查过的散步，
# 已经归到凉山的那条走过的路自己会改成西昌。
DIRECTORY_VERSION = 3

# v2（2026-09-08）：**`coastline` 这一列换了语义**。先前它装的是被画框裁碎的岸线线段，
# App 侧再接链、去重、沿画框围成海面；现在它装的是**闭合的海面环**——管线裁到画框、
# 把海面外环摆成顺时针、岛摆成逆时针，App 只按绕向填。
#
# 换语义必须升版本：旧版 App 拿到闭合环会走「一条开放链都没有」那条退路，
# 把整个画框铺成海再拿岛去挖，临海城市的图会整张变成水色。不靠它碰巧兼容。
MAP_DATA_VERSION = 2


# 区域 pbf 的中间产物放**仓库外**：过完标签的整国文件、每座城切出来的小 pbf，
# 一个国家几个 GB、上千个文件，而且全都可再生。
#
# 不是洁癖。这台机器的仓库一度在 iCloud 的「桌面与文档」同步里：切日本那 1739 座时，
# iCloudDriveCore 一直在同步这批临时文件，占掉 55–70% 的 CPU，osmium 只剩 40%，
# 一批从两分钟拖到二十分钟（2026-09-08 实测）。`~/Library/Caches` 正是「可再生的
# 中间产物」该待的地方——不同步、不进备份，系统缺盘时清掉也只是重跑一次 `country`。
WORK = Path.home() / "Library/Caches/cityatlas"
